type TranslationKey = keyof typeof reportTranslations['en'];

export const getReportTranslation = (key: string, language: string): string => {
  const lang = language === 'fr' ? 'fr' : 'en';
  return (reportTranslations[lang] as any)[key] || key;
};

export const getStatusLabel = (status: string, language: string): string => {
  const statusMap: Record<string, string> = {
    'paid': 'paid',
    'sent': 'sent',
    'overdue': 'overdue',
    'draft': 'draft',
    'pending': 'pending',
    'approved': 'approved',
    'rejected': 'rejected',
    'all': 'all'
  };
  
  const key = statusMap[status];
  const lang = language === 'fr' ? 'fr' : 'en';
  return key ? (reportTranslations[lang] as any)[key] : status;
};
