export type PlanType = 'free' | 'premium' | 'pro';

interface InvoiceDetail {
  invoice_number: string;
  issue_date: string;
  total: number;
  status: string;
  client_id: string;
}

interface RevenueByClientPdfOptions {
  clientRevenueData: ClientRevenueSummary;
  companyName?: string;
  startDate?: Date;
  endDate?: Date;
  companyFilterName?: string;
  invoiceDetails?: InvoiceDetail[];
  language?: 'fr' | 'en';
  returnBlob?: boolean;
  planType?: PlanType;
  hideBranding?: boolean;
}

